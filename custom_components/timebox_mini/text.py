def _normalize_text(text):
    text = str(text or "").strip()
    if not text:
        raise ValueError("Moving text action requires a non-empty text value")
    return "".join(char if 32 <= ord(char) <= 126 else "?" for char in text)


def _normalize_color(value, default):
    if value in (None, ""):
        return default

    if isinstance(value, (list, tuple)) and len(value) == 3:
        return tuple(max(0, min(255, int(channel))) for channel in value)

    try:
        return tuple(ImageColor.getrgb(str(value))[:3])
    except ValueError as err:
        raise ValueError("Expected color as #RRGGBB, color name, or RGB list") from err


def _glyph_rows(char):
    if char in ASCENDER_PIXEL_FONT:
        rows = ASCENDER_PIXEL_FONT[char]
        padding = ("." * len(rows[0]),) * (FONT_HEIGHT - ASCENDER_FONT_HEIGHT)
        return padding + rows

    if char in LOWERCASE_PIXEL_FONT:
        rows = LOWERCASE_PIXEL_FONT[char]
        padding = ("." * len(rows[0]),) * (FONT_HEIGHT - LOWERCASE_FONT_HEIGHT)
        return padding + rows

    return PIXEL_FONT.get(char, PIXEL_FONT["?fallback"])


def render_moving_text_frames(
    text,
    color=DEFAULT_TEXT_COLOR,
    background_color=DEFAULT_BACKGROUND_COLOR,
    direction="left",
    size=11,
    letter_spacing=DEFAULT_LETTER_SPACING,
):
    text = _normalize_text(text)
    foreground = _normalize_color(color, DEFAULT_TEXT_COLOR)
    background = _normalize_color(background_color, DEFAULT_BACKGROUND_COLOR)
    direction = str(direction or "left").lower()
    letter_spacing = max(0, int(letter_spacing or 0))

    if direction not in ("left", "right"):
        raise ValueError("Moving text direction must be 'left' or 'right'")

    glyphs = [_glyph_rows(char) for char in text]
    text_width = sum(len(rows[0]) for rows in glyphs)
    if len(glyphs) > 1:
        text_width += letter_spacing * (len(glyphs) - 1)

    text_width = max(1, text_width)

    canvas_width = text_width + (FONT_HEIGHT * 2)
    canvas = Image.new("RGBA", (canvas_width, FONT_HEIGHT), background + (255,))
    x = FONT_HEIGHT

    for rows in glyphs:
        for y, row in enumerate(rows):
            for column, pixel in enumerate(row):
                if pixel != ".":
                    canvas.putpixel((x + column, y), foreground + (255,))
        x += len(rows[0]) + letter_spacing

    offsets = range(0, canvas_width - FONT_HEIGHT + 1)
    if direction == "right":
        offsets = reversed(list(offsets))

    frames = [canvas.crop((offset, 0, offset + FONT_HEIGHT, FONT_HEIGHT)) for offset in offsets]
    if size != FONT_HEIGHT:
        frames = [frame.resize((size, size), Image.Resampling.NEAREST) for frame in frames]

    return frames
